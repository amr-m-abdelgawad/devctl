// Regenerates the embedded SPA blob that a `bun build --compile` binary cannot
// read from disk: presentation/web/assets.generated.ts. Copies drift;
// assets.test.ts fails until this script is re-run.
//
//   bun run build:web
import { createHash } from "node:crypto";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, relative } from "node:path";

const appRoot = dirname(import.meta.dir);
const webRoot = join(appRoot, "web");
const outModule = join(appRoot, "src", "presentation", "web", "assets.generated.ts");

export function listWebSources(root = webRoot): string[] {
  const out: string[] = [];
  const walk = (dir: string): void => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) {
        walk(full);
      } else {
        out.push(full);
      }
    }
  };
  walk(root);
  return out.sort();
}

export function hashWebSources(root = webRoot): string {
  const hash = createHash("sha256");
  for (const file of listWebSources(root)) {
    hash.update(relative(root, file));
    hash.update("\0");
    hash.update(readFileSync(file));
    hash.update("\0");
  }
  return hash.digest("hex");
}

function inlineAssets(html: string, dir: string): string {
  // Stylesheets first: inlined JS contains fake <link href="%s"> strings that
  // must not be treated as real tags.
  let out = html.replace(/<link\b([^>]*)\/?>/gi, (all, attrs: string) => {
    if (!/\brel="stylesheet"/i.test(attrs)) {
      return all;
    }
    const href = /\bhref="([^"]+)"/.exec(attrs);
    if (!href?.[1]) {
      return all;
    }
    const body = readFileSync(join(dir, href[1]), "utf8");
    return `<style>${body}</style>`;
  });
  out = out.replace(/<script\b([^>]*)><\/script>/gi, (all, attrs: string) => {
    const src = /\bsrc="([^"]+)"/.exec(attrs);
    if (!src?.[1]) {
      return all;
    }
    const body = readFileSync(join(dir, src[1]), "utf8");
    const rest = attrs.replace(/\bsrc="[^"]+"/i, "").replace(/\s+/g, " ").trim();
    return `<script${rest ? ` ${rest}` : ""}>${body}</script>`;
  });
  return out.replace(/https?:\/\/[^\s"'`<>\\]+/g, "");
}

export function renderWebAssetsModule(html: string, sourcesHash: string): string {
  return `// GENERATED by scripts/build-web-assets.ts — do not edit by hand.
// Source of truth: app/web/. Run \`bun run build:web\` after editing those
// files; assets.test.ts fails until this matches them.

export const WEB_INDEX_HTML = ${JSON.stringify(html)};
export const WEB_SOURCES_HASH = ${JSON.stringify(sourcesHash)};
`;
}

if (import.meta.main) {
  const outdir = mkdtempSync(join(tmpdir(), "devctl-web-"));
  mkdirSync(outdir, { recursive: true });
  try {
    const result = await Bun.build({
      entrypoints: [join(webRoot, "index.html")],
      target: "browser",
      minify: true,
      outdir,
      sourcemap: "none",
    });
    if (!result.success) {
      const logs = result.logs.map((log) => String(log)).join("\n");
      throw new Error(`Bun.build failed\n${logs}`);
    }
    const htmlFile = result.outputs.find((out) => out.path.endsWith(".html"))?.path
      ?? join(outdir, "index.html");
    const html = inlineAssets(readFileSync(htmlFile, "utf8"), dirname(htmlFile));
    const sourcesHash = hashWebSources(webRoot);
    writeFileSync(outModule, renderWebAssetsModule(html, sourcesHash));
    process.stdout.write(`wrote ${outModule}\n`);
  } finally {
    rmSync(outdir, { recursive: true, force: true });
  }
}
